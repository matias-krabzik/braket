-- Datos ficticios para probar relaciones y edición en Braket.
-- Se puede volver a ejecutar: no borra tablas ni reemplaza registros existentes.
CREATE DATABASE IF NOT EXISTS braket_relations_demo CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE braket_relations_demo;
CREATE TABLE IF NOT EXISTS Organizations (
    id BIGINT UNSIGNED PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    code CHAR(2) NOT NULL UNIQUE,
    country CHAR(2) NOT NULL,
    status ENUM('active','inactive') NOT NULL DEFAULT 'active',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Users (
    id BIGINT UNSIGNED PRIMARY KEY,
    organization_id BIGINT UNSIGNED NULL,
    manager_id BIGINT UNSIGNED NULL,
    employee_number VARCHAR(30) NOT NULL,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    status ENUM('active','pending','inactive') NOT NULL DEFAULT 'active',
    birth_date DATE NULL,
    last_seen DATETIME(6) NULL,
    reminder_time TIME NULL,
    CONSTRAINT fk_users_organization FOREIGN KEY (organization_id) REFERENCES Organizations(id),
    CONSTRAINT fk_users_manager FOREIGN KEY (manager_id) REFERENCES Users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS UserMappings (
    um_id BIGINT UNSIGNED PRIMARY KEY,
    user_id BIGINT UNSIGNED NOT NULL,
    external_user_id VARCHAR(60) NULL,
    migration_status ENUM('PENDING','COMPLETED','ERROR') NOT NULL DEFAULT 'PENDING',
    migration_at DATETIME NULL,
    error_message VARCHAR(200) NULL,
    CONSTRAINT fk_mappings_user FOREIGN KEY (user_id) REFERENCES Users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Departments (
    organization_id BIGINT UNSIGNED NOT NULL,
    code VARCHAR(16) NOT NULL,
    name VARCHAR(100) NOT NULL,
    PRIMARY KEY (organization_id, code),
    CONSTRAINT fk_departments_org FOREIGN KEY (organization_id) REFERENCES Organizations(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Employees (
    id BIGINT UNSIGNED PRIMARY KEY,
    organization_id BIGINT UNSIGNED NOT NULL,
    department_code VARCHAR(16) NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    job_title VARCHAR(100) NOT NULL,
    active TINYINT UNSIGNED NOT NULL DEFAULT 1,
    CONSTRAINT fk_employees_department FOREIGN KEY (organization_id, department_code)
        REFERENCES Departments(organization_id, code),
    CONSTRAINT fk_employees_user FOREIGN KEY (user_id) REFERENCES Users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS Orders (
    id BIGINT UNSIGNED PRIMARY KEY,
    user_id BIGINT UNSIGNED NOT NULL,
    approver_id BIGINT UNSIGNED NULL,
    total DECIMAL(12,2) NOT NULL,
    status ENUM('new','paid','cancelled') NOT NULL DEFAULT 'new',
    placed_at DATETIME NOT NULL,
    notes TEXT NULL,
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES Users(id),
    CONSTRAINT fk_orders_approver FOREIGN KEY (approver_id) REFERENCES Users(id)
) ENGINE=InnoDB;
